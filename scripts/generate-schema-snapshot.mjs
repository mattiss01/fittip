/**
 * Writes the schema as it stands today to one committed file.
 *
 * The migrations say how the schema got here: a changed function is restated
 * in full, so the 725 lines of `apply_rolling_plan_change_set` arrive as 725
 * new lines whatever changed in them. This file says where the schema is, so
 * its diff shows the lines that changed and nothing else (owner, 10 Nov 2026).
 *
 * It is generated, never edited, and never applied to anything: the migrations
 * stay the only way a database is built. The `database` job regenerates it
 * after its reset from zero and fails if the committed copy differs.
 */

import { spawnSync } from "node:child_process";
import { readFileSync, rmSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";

export class SchemaSnapshotError extends Error {}

const HEADER = [
  "-- Generated by `npm run schema:snapshot` from the local stack. Never edit it",
  "-- and never apply it: `supabase/migrations/` is what builds a database.",
  "-- These are the public and private schemas as those migrations leave them.",
  "",
  "",
].join("\n");

/**
 * What the CLI dumped, as the committed file. Line endings are made one kind
 * so a Windows run and CI's Linux run write the same bytes, and a dump that
 * holds no schema is refused rather than written over the committed file.
 */
export function cleanSchemaSnapshot(dump) {
  const body = dump.replace(/\r\n/g, "\n").trim();
  if (
    !/^CREATE TABLE /m.test(body) ||
    !/^CREATE (OR REPLACE )?FUNCTION /m.test(body)
  ) {
    throw new SchemaSnapshotError(
      "The Supabase CLI did not dump a schema. Is the local stack running?",
    );
  }
  return `${HEADER}${body}\n`;
}

const snapshotPath = "supabase/current-schema.sql";
if (
  process.argv[1] &&
  pathToFileURL(process.argv[1]).href === import.meta.url
) {
  // Dumped to a file of its own, not to stdout: the CLI can append a telemetry
  // error line there (`generate-database-types.mjs`), and not straight to the
  // committed path, so a failed dump leaves that as it was. Beside it rather
  // than in the temp directory: `npx.cmd` breaks on a quoted argument, and a
  // temp path can hold a space.
  const dumpPath = `${snapshotPath}.dump`;
  try {
    const dumped = spawnSync(
      `npx supabase db dump --local --schema public,private --file ${dumpPath}`,
      { encoding: "utf8", shell: true, maxBuffer: 64 * 1024 * 1024 },
    );
    if (dumped.status !== 0) {
      throw new SchemaSnapshotError(
        `supabase db dump failed: ${dumped.stderr?.trim() || dumped.error?.message || dumped.status}`,
      );
    }
    writeFileSync(
      snapshotPath,
      cleanSchemaSnapshot(readFileSync(dumpPath, "utf8")),
      "utf8",
    );
  } finally {
    rmSync(dumpPath, { force: true });
  }
  console.log(`${snapshotPath} regenerated from the local stack.`);
}
