import { describe, expect, it } from "vitest";

import {
  SchemaSnapshotError,
  cleanSchemaSnapshot,
} from "./generate-schema-snapshot.mjs";

const DUMP = [
  "CREATE OR REPLACE FUNCTION public.f() RETURNS void",
  "CREATE TABLE IF NOT EXISTS public.t (id uuid);",
].join("\r\n");

describe("cleanSchemaSnapshot", () => {
  it("writes the same bytes from a Windows dump and a Linux one", () => {
    const fromWindows = cleanSchemaSnapshot(`\r\n${DUMP}\r\n\r\n`);
    const fromLinux = cleanSchemaSnapshot(DUMP.replace(/\r\n/g, "\n"));
    expect(fromWindows).toBe(fromLinux);
    expect(fromWindows).not.toContain("\r");
    expect(fromWindows.endsWith(";\n")).toBe(true);
  });

  it("says first that the file is generated and never applied", () => {
    expect(cleanSchemaSnapshot(DUMP)).toMatch(/^-- Generated by /);
  });

  it("refuses a dump that holds no schema", () => {
    expect(() => cleanSchemaSnapshot("")).toThrow(SchemaSnapshotError);
    expect(() => cleanSchemaSnapshot("failed to connect to postgres")).toThrow(
      SchemaSnapshotError,
    );
  });
});
